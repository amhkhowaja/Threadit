#!/usr/bin/env bash
# Launch the FULL Threadit app locally on the Floci AWS emulator — no real AWS,
# no Cognito. Dev auth is stubbed (x-user-id). Great for contributors.
#
# Brings up, in order:
#   1. Floci emulator (docker compose)        -> :4566
#   2. Terraform apply (dev tfvars) to provision the dev stack into Floci
#   3. post_read  service (uvicorn)           -> :8080
#   4. post_write service (uvicorn)           -> :8081
#   5. Vite frontend                          -> :5173
#
# Logs: .run/*.log   PIDs: .run/*.pid   Stop everything: scripts/stop.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

RUN_DIR="$ROOT/.run"
mkdir -p "$RUN_DIR"
VENV="$ROOT/.venv"
PY="$VENV/bin/python"
FLOCI_ENDPOINT="http://localhost:4566"
READ_PORT="${READ_PORT:-8080}"
WRITE_PORT="${WRITE_PORT:-8081}"
FE_PORT="${FE_PORT:-5173}"
WEB_ORIGIN="http://localhost:${FE_PORT}"

export PYTHONPATH="$ROOT/libs/threadit_core:$ROOT"
# Floci / dev AWS env for the backend services.
export AWS_ACCESS_KEY_ID=test AWS_SECRET_ACCESS_KEY=test AWS_DEFAULT_REGION=us-east-1
export THREADIT_AWS_ENDPOINT_URL="$FLOCI_ENDPOINT"
export THREADIT_AWS_REGION=us-east-1
export THREADIT_TABLE_NAME=threadit
export THREADIT_CORS_ALLOW_ORIGINS="$WEB_ORIGIN"
export THREADIT_ATTACHMENTS_BUCKET="threadit-dev-images"
export THREADIT_ENVIRONMENT=dev

command -v docker >/dev/null || { echo "ERROR: docker not found"; exit 1; }
[[ -x "$PY" ]] || { echo "ERROR: venv missing. Run: make install"; exit 1; }

echo "==> 1/5 Starting Floci emulator (docker compose)"
docker compose up -d
# Wait for Floci to answer.
for i in $(seq 1 30); do
  if curl -s -m 2 "$FLOCI_ENDPOINT/_floci/health" >/dev/null 2>&1 || curl -s -m 2 "$FLOCI_ENDPOINT" >/dev/null 2>&1; then
    echo "    Floci is up."
    break
  fi
  sleep 1
done

echo "==> 2/5 Provisioning dev stack into Floci (terraform apply, ENV=dev)"
( cd "$ROOT/terraform" && terraform init -input=false >/dev/null && \
  terraform apply -input=false -auto-approve -var-file=envs/dev.tfvars >/dev/null ) \
  && echo "    dev stack provisioned." \
  || echo "    (terraform apply reported issues — services may still run against existing tables)"

start_svc() {
  local name="$1" module="$2" port="$3"
  echo "==> Starting $name on :$port"
  ( "$VENV/bin/uvicorn" "$module:app" --host 127.0.0.1 --port "$port" \
      >"$RUN_DIR/$name.log" 2>&1 & echo $! > "$RUN_DIR/$name.pid" )
}

echo "==> 3/5 + 4/5 Backend services"
start_svc post_read  services.post_read.app  "$READ_PORT"
start_svc post_write services.post_write.app "$WRITE_PORT"

# Wait for both to answer /healthz.
for pair in "read:$READ_PORT" "write:$WRITE_PORT"; do
  port="${pair##*:}"
  for i in $(seq 1 20); do
    curl -s -m 2 "http://127.0.0.1:$port/healthz" >/dev/null 2>&1 && break
    sleep 0.5
  done
done
echo "    read  -> http://127.0.0.1:$READ_PORT/healthz : $(curl -s -m2 http://127.0.0.1:$READ_PORT/healthz || echo DOWN)"
echo "    write -> http://127.0.0.1:$WRITE_PORT/healthz : $(curl -s -m2 http://127.0.0.1:$WRITE_PORT/healthz || echo DOWN)"

echo "==> Writing frontend/.env.local (target: Floci/local, dev auth)"
cat > "$ROOT/frontend/.env.local" <<EOF
# Generated by scripts/run-floci.sh — backend target: Floci/local (do not commit).
VITE_API_BASE_URL=http://127.0.0.1:${READ_PORT}
VITE_WRITE_BASE_URL=http://127.0.0.1:${WRITE_PORT}
VITE_DEV_USER_ID=dev-user-local
VITE_FEATURE_SEARCH=true
VITE_FEATURE_IMAGES=true
VITE_COGNITO_REGION=
VITE_COGNITO_USER_POOL_ID=
VITE_COGNITO_CLIENT_ID=
VITE_COGNITO_DOMAIN=
VITE_REDIRECT_URI=
EOF

cd "$ROOT/frontend"
[[ -d node_modules ]] || { echo "==> npm install"; npm install; }

echo "==> 5/5 Starting frontend (Vite) on :$FE_PORT"
( npx vite --port "$FE_PORT" --strictPort >"$RUN_DIR/frontend.log" 2>&1 & echo $! > "$RUN_DIR/frontend.pid" )
for i in $(seq 1 20); do
  curl -s -m 2 "http://localhost:$FE_PORT" >/dev/null 2>&1 && break
  sleep 0.5
done

echo
echo "============================================================"
echo "  Threadit — FULL LOCAL stack on Floci (dev auth)"
echo "  Frontend : http://localhost:${FE_PORT}"
echo "  Read API : http://127.0.0.1:${READ_PORT}"
echo "  Write API: http://127.0.0.1:${WRITE_PORT}"
echo "  Logs     : .run/*.log"
echo "  Stop all : make app-stop   (or scripts/stop.sh)"
echo "============================================================"
