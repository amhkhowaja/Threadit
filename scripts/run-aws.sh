#!/usr/bin/env bash
# Launch Threadit frontend locally against the REAL AWS backend (ALB + Cognito).
#
# It reads the live endpoints straight from Terraform outputs (prodweb state),
# writes frontend/.env.local, and starts Vite on :5173 (the port Cognito's
# callback is registered for).
#
# Prereqs: the AWS stack is deployed (see `make aws-up`), terraform + node installed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

TF_DIR="$ROOT/terraform"
TF_STATE="${TF_STATE:-prodweb.tfstate}"
PORT="${PORT:-5173}"
REGION="${REGION:-eu-central-1}"

command -v terraform >/dev/null || { echo "ERROR: terraform not found on PATH"; exit 1; }
command -v node >/dev/null       || { echo "ERROR: node not found on PATH"; exit 1; }

echo "==> Reading backend endpoints from terraform ($TF_STATE)"
tf_out() { terraform -chdir="$TF_DIR" output -state="$TF_STATE" -raw "$1" 2>/dev/null || true; }

ALB_DNS="$(tf_out alb_dns)"
POOL_ID="$(tf_out cognito_user_pool_id)"
CLIENT_ID="$(tf_out cognito_app_client_id)"
HOSTED_DOMAIN="$(tf_out cognito_hosted_domain)"

if [[ -z "$ALB_DNS" || -z "$POOL_ID" || -z "$CLIENT_ID" ]]; then
  echo "ERROR: could not read AWS outputs from $TF_STATE."
  echo "       Is the stack deployed? Try: make aws-up"
  exit 1
fi

API_BASE="http://${ALB_DNS}"
# hosted_domain may already include https://; normalize.
case "$HOSTED_DOMAIN" in
  https://*) COGNITO_DOMAIN="$HOSTED_DOMAIN" ;;
  "")        COGNITO_DOMAIN="" ;;
  *)         COGNITO_DOMAIN="https://${HOSTED_DOMAIN}" ;;
esac

ENV_FILE="$ROOT/frontend/.env.local"
echo "==> Writing $ENV_FILE (target: AWS)"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/run-aws.sh — backend target: REAL AWS (do not commit).
VITE_API_BASE_URL=${API_BASE}
VITE_FEATURE_SEARCH=true
VITE_FEATURE_IMAGES=true
VITE_COGNITO_REGION=${REGION}
VITE_COGNITO_USER_POOL_ID=${POOL_ID}
VITE_COGNITO_CLIENT_ID=${CLIENT_ID}
VITE_COGNITO_DOMAIN=${COGNITO_DOMAIN}
VITE_REDIRECT_URI=http://localhost:${PORT}/auth/callback
EOF

echo "==> Backend health check: ${API_BASE}/healthz"
if command -v curl >/dev/null; then
  curl -s -m 8 "${API_BASE}/healthz" || echo "(health check did not respond — the ALB may be waking up)"
  echo
fi

cd "$ROOT/frontend"
[[ -d node_modules ]] || { echo "==> npm install"; npm install; }

echo
echo "============================================================"
echo "  Threadit — LOCAL frontend  ->  AWS backend"
echo "  Frontend : http://localhost:${PORT}"
echo "  API (ALB): ${API_BASE}"
echo "  Auth     : real Cognito sign-in (${COGNITO_DOMAIN})"
echo "  Stop     : Ctrl-C"
echo "============================================================"
echo

exec npx vite --port "$PORT" --strictPort
